<script>
import { authApi, setToken } from '../../common/api.js'
export default {
  name: 'PageLogin',
  data() { return { loginId:'', password:'', showPwd:false, agreed:false, error:'', loading:false, rememberPwd:false } },
  mounted() { this.loadRemembered() },
  methods: {
    clearError(){this.error=''},
    loadRemembered() {
      const savedId = localStorage.getItem('remembered_login_id')
      const savedPwd = localStorage.getItem('remembered_password')
      if (savedId) {
        this.loginId = savedId
        this.rememberPwd = !!savedPwd
        if (savedPwd) {
          this.password = savedPwd
        }
      }
    },
    async handleLogin() {
      if(!this.loginId.trim()){this.error='请输入用户名';return}
      if(!this.password){this.error='请输入密码';return}
      if(!this.agreed){this.error='请先阅读并同意用户协议和隐私政策';return}
      this.error='';this.loading=true
      try{
        const data=await authApi.login(this.loginId.trim(),this.password)
        setToken({...data,loginId:this.loginId.trim()})
        // 记住密码处理
        if (this.rememberPwd) {
          localStorage.setItem('remembered_login_id', this.loginId)
          localStorage.setItem('remembered_password', this.password)
        } else {
          localStorage.removeItem('remembered_password')
          localStorage.removeItem('remembered_login_id')
        }
        this.$router.replace({name:'home'})
      }
      catch(e){this.error=e.message||'登录失败'}finally{this.loading=false}
    }
  }
}
</script>

